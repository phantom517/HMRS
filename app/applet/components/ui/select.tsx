        "relative flex w-full cursor-pointer items-center justify-between gap-2 rounded-lg py-2 pr-8 pl-3 text-sm text-[var(--ink)] outline-none select-none transition-colors hover:bg-[var(--linen)] focus:bg-[var(--linen)] data-highlighted:bg-[var(--linen)] data-disabled:pointer-events-none data-disabled:opacity-40 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
